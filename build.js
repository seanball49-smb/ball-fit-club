// Vercel runs this on every deploy (see vercel.json).
// It copies the app into dist/ and writes dist/config.js from your
// Vercel Environment Variables, so the keys never need to be in GitHub.
// No packages needed: it only uses Node's built-in modules.

const fs = require('fs');
const path = require('path');

const root = __dirname;
const out = path.join(root, 'dist');
const files = ['index.html', 'styles.css', 'app.js', 'manifest.webmanifest', 'icons'];

fs.rmSync(out, { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });
for (const f of files) {
  fs.cpSync(path.join(root, f), path.join(out, f), { recursive: true });
}

// Stamp every deploy with a unique version so phones always load the newest
// files instead of an old copy they saved earlier.
const v = (process.env.VERCEL_GIT_COMMIT_SHA || Date.now().toString(36)).slice(0, 10);
const stamp = (file, pairs) => {
  const p = path.join(out, file);
  let s = fs.readFileSync(p, 'utf8');
  for (const [from, to] of pairs) s = s.split(from).join(to);
  fs.writeFileSync(p, s);
};
stamp('index.html', [['/app.js"', `/app.js?v=${v}"`], ['/styles.css"', `/styles.css?v=${v}"`]]);
stamp('app.js', [["from './config.js'", `from './config.js?v=${v}'`]]);
const appCheck = fs.readFileSync(path.join(out, 'app.js'), 'utf8');
console.log(`App version ${v} — uses ${appCheck.includes('fit_profiles') ? 'fit_ tables (new)' : 'OLD table names — upload the new app.js to GitHub'}.`);

const env = process.env;
// Keep only https://<project>.supabase.co, dropping anything after it
// (like /rest/v1/ or a trailing slash), which Supabase rejects.
let url = (env.SUPABASE_URL || env.NEXT_PUBLIC_SUPABASE_URL || '').trim().replace(/^["']|["']$/g, '');
if (url) {
  if (!/^https?:\/\//i.test(url)) url = 'https://' + url;
  try { url = new URL(url).origin; } catch { console.warn('⚠️  SUPABASE_URL does not look like a web address: ' + url); }
}
const key = (env.SUPABASE_ANON_KEY || env.SUPABASE_PUBLISHABLE_KEY ||
             env.NEXT_PUBLIC_SUPABASE_ANON_KEY || env.NEXT_PUBLIC_SUPABASE_PUBLISHABLE_KEY || '').trim();

if (!url || !key) {
  console.warn('\n⚠️  SUPABASE_URL and/or SUPABASE_ANON_KEY are not set in Vercel.');
  console.warn('   The app will deploy but show a setup message until you add them and redeploy.\n');
}
if (/service_role|sb_secret_/.test(key)) {
  console.error('\n✋ That key is a SECRET key. Use the publishable / anon public key instead.\n');
  process.exit(1);
}

fs.writeFileSync(
  path.join(out, 'config.js'),
  `// Generated by build.js from Vercel Environment Variables. Do not edit.\n` +
  `export const SUPABASE_URL = ${JSON.stringify(url || 'PASTE_YOUR_PROJECT_URL_HERE')};\n` +
  `export const SUPABASE_ANON_KEY = ${JSON.stringify(key || 'PASTE_YOUR_PUBLIC_KEY_HERE')};\n`
);

console.log(`Built dist/ — Supabase URL ${url ? 'set' : 'MISSING'}, key ${key ? 'set' : 'MISSING'}.`);
